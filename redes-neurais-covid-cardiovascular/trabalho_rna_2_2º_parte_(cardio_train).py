import pandas as pd
import numpy as np
from sklearn.neural_network import MLPClassifier
from sklearn.model_selection import LeaveOneOut
from sklearn.model_selection import train_test_split
import matplotlib.pyplot as plt
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import r2_score

#Leitura da base de dados
data = pd.read_csv('cardio_train.csv',  sep = ';')
data.head()

data.info()

"""Pre-processamento"""

data = data.drop(['id'],axis=1)
data

data.shape

#Retornar quantidade de dados vazios de cada coluna
data.isnull().sum()

data_sample = data.sample(n=10000)

#Separando o target
X = data_sample.drop(['cardio'],axis=1)
y = data_sample['cardio']
X

y

"""Aplicando o método de validação cruzada  Holdout"""

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=0)

#Aplicação do MultLayerPerceptron com hidden_layer_sizes=(50) e activation=’relu’
rna = MLPClassifier(hidden_layer_sizes=(50), activation = 'relu')

#Passando os parametros para treinamento
rna.fit(X_train, y_train)

#Previsão do conjunto de teste
y_rna_pred = rna.predict(X_test)

from sklearn.metrics import accuracy_score
acc = accuracy_score(y_test,y_rna_pred)
print('Acurácia: ', acc)

