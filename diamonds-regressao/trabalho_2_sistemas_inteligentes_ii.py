label_data.head()

#Separando as colunas principais da coluna que será utilizada para comparação(preço)
X = label_data.drop(["price"],axis =1)
y= label_data["price"]

"""Aplicação do metodo de regressão"""

import time

from sklearn import preprocessing
from sklearn import decomposition
from sklearn import model_selection
from sklearn import metrics
from sklearn.model_selection import train_test_split
from sklearn.model_selection import GridSearchCV
from sklearn.svm import SVR #Maquina de vetor suporte
from sklearn.neighbors import KNeighborsRegressor #K vizinhos mais proximos
from sklearn.tree import DecisionTreeRegressor #Arvore de decisão

from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error, make_scorer #Métricas

regressors = [
      (
          "Nearest Neighbors",'KNN',		KNeighborsRegressor(),
	        {'n_neighbors':[1,2,3,4,5,6,10], 'weights':['uniform', 'distance']}
      ),

      (
        "Decision Tree",'DT',		DecisionTreeRegressor(),
        {'max_depth':[None, 1,2,3,4,5]},
      ),
]

list_models=[]
#no mínimo 30 vezes
for run in range(30):
    for name, clf_name, clf, clf_param_grid in regressors:#[::-1]:
      np.random.seed(run)


      n_folds=5
      cv = model_selection.KFold(n_splits=n_folds, shuffle=True, random_state=run)

      clf_gcv=model_selection.GridSearchCV(estimator=clf, param_grid=clf_param_grid, cv=cv, scoring=make_scorer(r2_score), n_jobs=-1, verbose=0)

      st = time.time()
      for train, test in cv.split(X):
          X_train, X_test = X.values[train], X.values[test]
          y_train, y_test = y.values[train], y.values[test]

      clf_gcv.fit(X_train,y_train)

      #print(clf_gcv.best_params_)

      y_pred = clf_gcv.predict(X_test)

      st = time.time()-st


      print(run, clf_name, r2_score(y_test, y_pred), \
                mean_absolute_error(y_test, y_pred), \
                mean_squared_error(y_test, y_pred), \
                clf_gcv.best_params_)

      l = {
        'DATASET'   : 'Diamonds'                    ,
        'MODEL'     : clf_name                      ,
        'RUN'       : run                           ,
        'BEST_PARAMS'   : clf_gcv.best_params_                  ,
        'TIME'      : st                            ,
        'Y_TRUE'        : y_test                        ,
        'Y_PRED'        : y_pred                        ,
        'R2'        : r2_score(y_test,y_pred)           ,
        'MAE'       : mean_absolute_error(y_test,y_pred)            ,
        'MSE'       : mean_squared_error(y_test,y_pred)             ,
        }

      list_models.append(l)

aux = pd.DataFrame(list_models)

#selecionando modelos
