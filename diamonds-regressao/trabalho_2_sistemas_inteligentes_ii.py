#Copiando os dados originais
label_data = data.copy()

encoder = LabelEncoder();

# Aplicando o label encoder em todas as colunas de dados categoricos
label_data['cut'] = encoder.fit_transform(label_data['cut'])
label_data['color'] = encoder.fit_transform(label_data['color'])
