def fun_knn_fs(x,*args):
  X, y, flag, n_splits, random_seed = args
  n_samples, n_var = X.shape
  w = {0 :'uniform', 1 :'distance', }

  p={
      'p': int(round(x[2])),
      'n_neighbors': int(round(x[0])),
      'weights':w[int(round(x[1]))],
  }

  clf = KNeighborsRegressor()
  clf.set_params(**p)

  try:

    cv=KFold(n_splits=n_splits, shuffle=True, random_state=int(random_seed))
    y_p  = cross_val_predict(clf,X, y, cv=cv, n_jobs=-1)

    r =  mean_squared_error(y,y_p)
  except:
    y_p=[None]
    r=1e12

  #print(r,'\t',p)
  if flag=='eval':
      return r
  else:
    return {'Y_TRUE':y, 'Y_PRED':y_p, 'BEST_PARAMS':p, 'PARAMS':x, 'EST_NAME':'KNN',
              'ESTIMATOR':clf, 'DATA':X, 'SEED':random_seed}

def fun_dtc_fs(x,*args):
  X, y, flag, n_splits, random_seed = args
  n_samples, n_var = X.shape
  clf = DecisionTreeRegressor(random_state=random_seed,)
  p={
     'max_depth':  int(x[0]),
     'min_samples_split': int(x[1]),
    }
  clf.set_params(**p)

  try:

    cv=KFold(n_splits=n_splits, shuffle=True, random_state=int(random_seed))
    y_p  = cross_val_predict(clf,X, y, cv=cv, n_jobs=-1)

    r =  mean_squared_error(y,y_p)
  except:
    y_p=[None]
    r=1e12

  #print(r,'\t',p)
  if flag=='eval':
      return r
  else:
    return {'Y_TRUE':y, 'Y_PRED':y_p, 'BEST_PARAMS':p, 'PARAMS':x, 'EST_NAME':'DT',
              'ESTIMATOR':clf, 'DATA':X, 'SEED':random_seed}

